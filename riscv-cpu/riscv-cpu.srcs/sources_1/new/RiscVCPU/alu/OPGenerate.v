`timescale 1ns / 1ps
//////////////////////////////////////////////////////////////////////////////////
// 运算信号生成逻辑（完整版：24 条基本指令 + CCAB 扩展指令全集）
// functOP = {IR[30], IR[26], IR[25], IR[14:12], IR[6:2]}（11 位）
//////////////////////////////////////////////////////////////////////////////////


module ALU_OPGenerate(
    input       [31:0]  IR,
    output  reg [3:0]   ALUOP
    );
    reg [10:0]   functOP;
    always @(*) functOP = {IR[30],IR[26],IR[25],IR[14:12],IR[6:2]};

    always @(*)
        casez(functOP)
            // ---------- R 型 ----------
            11'b00000001100: ALUOP = 5;  //ADD
            11'b10000001100: ALUOP = 6;  //SUB
            11'b00000101100: ALUOP = 0;  //SLL
            11'b00010101100: ALUOP = 2;  //SRL
            11'b10010101100: ALUOP = 1;  //SRA
            11'b00010001100: ALUOP = 9;  //XOR
            11'b00011101100: ALUOP = 7;  //AND
            11'b00011001100: ALUOP = 8;  //OR
            11'b00001001100: ALUOP = 11; //SLT
            11'b00001101100: ALUOP = 12; //SLTU
            11'b00100001100: ALUOP = 3;  //MUL
            11'b00110101100: ALUOP = 4;  //DIVU
            11'b00111101100: ALUOP = 4;  //REMU（余数经 Result2 写回）
            // ---------- I 型运算 ----------
            11'b???00000100: ALUOP = 5;  //ADDI
            11'b???11100100: ALUOP = 7;  //ANDI
            11'b???11000100: ALUOP = 8;  //ORI
            11'b???10000100: ALUOP = 9;  //XORI
            11'b???01000100: ALUOP = 11; //SLTI
            11'b???01100100: ALUOP = 12; //SLTIU
            11'b00000100100: ALUOP = 0;  //SLLI
            11'b00010100100: ALUOP = 2;  //SRLI
            11'b10010100100: ALUOP = 1;  //SRAI
            // ---------- 访存 ----------
            11'b???00000000: ALUOP = 5;  //LB
            11'b???10000000: ALUOP = 5;  //LBU
            11'b???00100000: ALUOP = 5;  //LH
            11'b???10100000: ALUOP = 5;  //LHU
            11'b???01000000: ALUOP = 5;  //LW
            11'b???00001000: ALUOP = 5;  //SB
            11'b???00101000: ALUOP = 5;  //SH
            11'b???01001000: ALUOP = 5;  //SW
            // ---------- 分支（比较结果供 EX 判定，Result 本身不使用） ----------
            11'b???00011000: ALUOP = 6;  //BEQ
            11'b???00111000: ALUOP = 6;  //BNE
            11'b???10011000: ALUOP = 11; //BLT
            11'b???10111000: ALUOP = 11; //BGE
            11'b???11011000: ALUOP = 12; //BLTU
            11'b???11111000: ALUOP = 12; //BGEU
            // ---------- 跳转 ----------
            11'b??????11011: ALUOP = 5;  //JAL
            11'b???00011001: ALUOP = 5;  //JALR
            // ---------- U 型 ----------
            11'b??????01101: ALUOP = 0;  //LUI（写回值在 WB 段直接由 IR 生成）
            11'b??????00101: ALUOP = 5;  //AUIPC（写回值在 WB 段直接由 PC+imm 生成）
            default:        ALUOP = 0;
        endcase
endmodule
